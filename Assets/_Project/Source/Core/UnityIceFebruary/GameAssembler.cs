namespace UnityIceFebruary
{
    using UnityEngine;
    using IceFebruary.Time;
    using IceFebruary.Physics;
    using IceFebruary;

    using IceVector2 = IceFebruary.Space.Vector2;

    public class GameAssembler : MonoBehaviour
    {
        [Header("Base settings:")]
        [SerializeField] private int _startCyclesBufferSize = 128;
        [SerializeField] private int _overlapCollidersBufferLength = 64;
        [SerializeField] private GameInputAction _gameInputAction;
        [Header("Stickman settings:")]
        [SerializeField] private StickmanSpawnList_AUTOGENERATED _stickmanSpawnList;

        private ITime _time;
        private IPhysics2D _physics2D;
        private IObjectManager _objectManager;

        private IInputProvider _input;

        private StickmanFactory _stickmanFactory;

        private void Awake()
        {
            _time = new UnityTime(_startCyclesBufferSize);
            _physics2D = new UnityPhysics2D(_overlapCollidersBufferLength);
            _objectManager = new UnityObjectManager();

            _input = new UnityPlayerInputProvider(_gameInputAction);

            StickmanSpawnList stickmanSpawnList = _stickmanSpawnList.ToPoco();

            _stickmanFactory = new(_time, _physics2D, _objectManager, stickmanSpawnList.StickmanPrefab);

            CreateNewActiveStickman(stickmanSpawnList.PlayerSpawnsSetting.Position, out StickmanConfig playerStickmanConfig)
                .SetPlayerControl(_input);

            for (int index = 0; index < stickmanSpawnList.EnemiesSpawnSettings.Length; index++)
                CreateNewActiveStickman(stickmanSpawnList.EnemiesSpawnSettings[index].Position, out _)
                    .SetEnemyControl(playerStickmanConfig.PickUpSettings.StickmanPosition);
        }
        private StickmanBuilder CreateNewActiveStickman(IceVector2 position, out StickmanConfig stickmanConfig) => _stickmanFactory.Create(position, out stickmanConfig).SetUp();
        private void Update() => _time.DoFrame(Time.deltaTime);
        private void FixedUpdate() => _time.DoFixedFrame();
    }
}
